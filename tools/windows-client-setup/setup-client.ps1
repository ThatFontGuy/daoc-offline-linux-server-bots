# Set up the Offline DAoC client for a specific server (PowerShell 5+, run on Windows).
#
# This does NOT contain any game files. It downloads the official installer fresh from
# shadowofze/OfflineDAoC (https://github.com/shadowofze/OfflineDAoC) each time it runs, the same
# installer you'd get from their release page, then adds one small file of its own: a shortcut
# that connects straight to a server you choose, bypassing the installer's own single-player
# launcher (which always starts its own separate local server).
#
# Usage: double-click Setup-Client.cmd (it calls this script), or run directly:
#   powershell -ExecutionPolicy Bypass -File setup-client.ps1 [-ReleaseVersion 0.37b]
#
# -ReleaseVersion should match the Offline DAoC version the server you're connecting to tracks
# (check with ./daoc-admin status on the server). It does not have to be exact - the server
# enforces what classes/content are actually available regardless of which client edition you
# install - but matching avoids protocol-version surprises.
param(
    [string]$ReleaseVersion = '0.37b'
)
$ErrorActionPreference = 'Stop'

Write-Host "=== DAoC server client setup ===" -ForegroundColor Cyan
Write-Host "Downloads the official Offline DAoC client (shadowofze/OfflineDAoC, not hosted by this"
Write-Host "project) and creates a shortcut that connects straight to a server you choose."
Write-Host ""

$ServerAddress = Read-Host "Server address (ask whoever invited you - an IP or hostname)"
if (-not $ServerAddress) { throw "A server address is required." }
$Account = Read-Host "Account name to create (pick anything; it's created on first connect)"
if (-not $Account) { throw "An account name is required." }
$Password = Read-Host "Account password to create (avoid %, &, ^, | - batch files handle those poorly)"
if (-not $Password) { throw "A password is required." }

$DefaultInstall = Join-Path $PSScriptRoot "OfflineDAoC-v$ReleaseVersion"
$InstallInput = Read-Host "Install folder [$DefaultInstall]"
$InstallFolder = if ($InstallInput) { $InstallInput } else { $DefaultInstall }

if (Test-Path -LiteralPath $InstallFolder) {
    throw "`"$InstallFolder`" already exists. Pick a new, empty folder - the official installer refuses to overwrite an existing game (to protect saves)."
}

$work = Join-Path $PSScriptRoot ".setup-work"
New-Item -ItemType Directory -Path $work -Force | Out-Null
$zipName = "Download-OfflineDAoC-v$ReleaseVersion.zip"
$zipPath = Join-Path $work $zipName

Write-Host ""
Write-Host "Downloading the official installer from shadowofze/OfflineDAoC (not hosted by this project) ..." -ForegroundColor Cyan
Invoke-WebRequest -UseBasicParsing `
    -Uri "https://github.com/shadowofze/OfflineDAoC/releases/download/v$ReleaseVersion/$zipName" `
    -OutFile $zipPath

Expand-Archive -LiteralPath $zipPath -DestinationPath $work -Force
$downloaderScript = Get-ChildItem -Path $work -Filter "Get-OfflineDAoC.ps1" -Recurse | Select-Object -First 1
if (-not $downloaderScript) { throw "Could not find Get-OfflineDAoC.ps1 after extracting the official installer zip." }

Write-Host ""
Write-Host "Downloading and installing the game (about 5 GB) into `"$InstallFolder`" ..." -ForegroundColor Cyan
Write-Host "This is shadowofze/OfflineDAoC's own official installer running now, not a separate program."
Write-Host ""
& $downloaderScript.FullName -Destination $InstallFolder -ReleaseVersion $ReleaseVersion
if ($LASTEXITCODE -and $LASTEXITCODE -ne 0) {
    throw "The official installer reported an error (exit code $LASTEXITCODE). See its messages above."
}

Write-Host ""
Write-Host "Looking for connect.exe inside the installed game ..." -ForegroundColor Cyan
$connect = Get-ChildItem -Path $InstallFolder -Filter "connect.exe" -Recurse -ErrorAction SilentlyContinue | Select-Object -First 1
if (-not $connect) {
    throw "Could not find connect.exe anywhere under `"$InstallFolder`". The install may have failed - check the messages above, or look for it yourself and run it as: connect.exe game.dll $ServerAddress $Account <password>"
}

$shortcutPath = Join-Path $connect.DirectoryName "CONNECT TO SERVER.cmd"
$shortcutLines = @(
    "@echo off",
    "rem Connects directly to your DAoC server, bypassing the single-player launcher.",
    "rem Generated by tools/windows-client-setup/setup-client.ps1 - see GETTING-STARTED.md.",
    "set SERVER=$ServerAddress",
    "set ACCOUNT=$Account",
    "set PASSWORD=$Password",
    "",
    "connect.exe game.dll %SERVER% %ACCOUNT% %PASSWORD%",
    "pause"
)
Set-Content -LiteralPath $shortcutPath -Value $shortcutLines -Encoding ASCII

Write-Host ""
Write-Host "Done! Created:" -ForegroundColor Green
Write-Host "  $shortcutPath"
Write-Host "Double-click that file any time you want to play - no need to run this setup again."
Write-Host ""
$launchNow = Read-Host "Connect now? (y/n)"
if ($launchNow -eq 'y') {
    Start-Process -FilePath $shortcutPath -WorkingDirectory $connect.DirectoryName
}
